/* ----------------------------
   DEFAULT STORYBOARD LINKS
---------------------------- */
function initDefaultStoryboardLinks() {
    const MAX_ATTEMPTS = 80;
    let attempts = 0;

    const map = {
        def_aoe: "Ash of Endhal",
        def_oxy: "Oxyvoris | The Uprising",
        def_chaos: "Chaos Circuit | A Symphony of Madness"
    };

    function waitForDB() {
        attempts++;
        if (!Array.isArray(window.storyboardDatabase)) return false;

        Object.entries(map).forEach(([id, title]) => {
            const el = document.getElementById(id);
            if (!el) return;

            const sb = window.storyboardDatabase.find(s => s.title === title);
            if (!sb) return;

            attachStoryboardLightbox(el, sb);
        });

        return true;
    }

    if (waitForDB()) return;

    const interval = setInterval(() => {
        if (waitForDB() || attempts >= MAX_ATTEMPTS) {
            clearInterval(interval);
        }
    }, 100);
}

function attachStoryboardLightbox(el, sb) {
    if (!el || !sb) return;

    el.addEventListener("click", (e) => {
        e.preventDefault();
        openStoryboardPlayer(sb, el);
    });
}

/* ----------------------------
   PLAYER FACTORY
---------------------------- */
function createStoryboardPlayer(sb, boardLight) {

    const panels = Array.isArray(sb.panels) ? sb.panels : [];
    const concept = Array.isArray(sb.conceptArt) ? sb.conceptArt : [];

const state = {
    index: 0,
    playing: false,
    interval: null,
    speed: 1,
    rateLabel: "1X"
};

    const imgEl = document.getElementById("board_img");
    const frameNum = document.getElementById("frame_number");
    const frameSlide = document.getElementById("frame_slide");
    const display = document.getElementById("board_display");

    function getInterval() {
        return 1000 / (2 * state.speed);
    }

    function update() {
        const p = panels[state.index];
        if (!p) return;

        imgEl.src = p.src;
        frameNum.textContent = state.index + 1;

        const pct = panels.length > 1
            ? (state.index / (panels.length - 1)) * 100
            : 0;

        frameSlide.style.width = pct + "%";
    }

    function stop() {
        state.playing = false;
        clearInterval(state.interval);
        state.interval = null;
		document.getElementById("forward").style.display = "";
		document.getElementById("backward").style.display = "";
		document.getElementById("play_board").style.display = "";
		document.getElementById("exit_board").style.display = "";
    }

function play() {
    if (!panels.length) return;

    if (state.index >= panels.length - 1) {
        state.index = 0;
        update();
    }

    state.playing = true;
	
	document.getElementById("forward").style.display = "none";
	document.getElementById("backward").style.display = "none";
	document.getElementById("play_board").style.display = "none";
	document.getElementById("exit_board").style.display = "none";

    state.interval = setInterval(() => {
        state.index++;

        if (state.index >= panels.length) {
            stop();
            return;
        }

        update();
    }, getInterval());
}

    function restartIfPlaying() {
        if (!state.playing) return;

        clearInterval(state.interval);

state.interval = setInterval(() => {
    state.index = (state.index + 1) % panels.length;
    update();
}, getInterval());
    }

    panels.forEach((p, i) => {
        const wrap = document.createElement("div");
        wrap.className = "story_wrap";

        const img = document.createElement("img");
        img.src = p.src;

        wrap.appendChild(img);

        wrap.addEventListener("click", () => {
            stop();
            state.index = i;
            update();
        });

        display.appendChild(wrap);
    });

    document.getElementById("play_board").onclick = () => (state.playing ? stop() : play());
    document.getElementById("con_act").onclick = () => (state.playing ? stop() : play());
    imgEl.onclick = () => (state.playing ? stop() : play());

    document.getElementById("forward").onclick = () => {
        stop();
        state.index = (state.index + 1) % panels.length;
        update();
    };

    document.getElementById("backward").onclick = () => {
        stop();
        state.index = (state.index - 1 + panels.length) % panels.length;
        update();
    };

    const frames = document.getElementById("frames");
    let dragging = false;

    function setFrameFromX(x) {
        const rect = frames.getBoundingClientRect();
        const pos = Math.max(0, Math.min(1, (x - rect.left) / rect.width));
        state.index = Math.round(pos * (panels.length - 1));
        update();
    }

    frames?.addEventListener("mousedown", (e) => {
        stop();
        dragging = true;
        setFrameFromX(e.clientX);
        document.body.style.userSelect = "none";
    });

    document.addEventListener("mousemove", (e) => {
        if (!dragging) return;
        setFrameFromX(e.clientX);
    });

    document.addEventListener("mouseup", () => {
        dragging = false;
        document.body.style.userSelect = "";
    });

    const frameCount = document.getElementById("frame_count");

    frameCount?.addEventListener("click", () => {
        if (state.playing) stop();

        const input = document.createElement("input");
        input.type = "text";
        input.id = "active_frame";
        input.value = frameNum.textContent.trim();
        input.maxLength = 4;

        frameCount.replaceWith(input);
        input.focus();

        function commit() {
            let val = parseInt(input.value, 10);
            if (isNaN(val)) val = 1;

            state.index = Math.max(0, Math.min(panels.length - 1, val - 1));
            update();

            input.replaceWith(frameCount);
        }

        input.addEventListener("keydown", e => {
            if (e.key === "Enter") commit();
            if (e.key === "Escape") input.replaceWith(frameCount);
        });

        input.addEventListener("blur", commit);
    });

    const boardRateEl = document.getElementById("board_rate");

    if (boardRateEl) {
        const rates = [
            { text: ".5X", value: 0.5 },
            { text: "1X", value: 1 },
            { text: "1.5X", value: 1.5 },
            { text: "2X", value: 2 }
        ];

        function restore(label = "1X") {
            boardRateEl.querySelectorAll(".rate").forEach(e => e.remove());
            const active = document.getElementById("rate_active");
            if (active) active.remove();

            const p = document.createElement("p");
            p.id = "rate_active";
            p.textContent = label;
            boardRateEl.appendChild(p);
        }

        function openMenu() {
            const active = document.getElementById("rate_active");
            if (active) active.remove();
			
			boardRateEl.style.height = "10.5em";
			
			boardRateEl.style.background = "#000000";
			boardRateEl.style.color = "#ffffff";

            rates.forEach(opt => {
                const p = document.createElement("p");
                p.className = "rate";
                p.textContent = opt.text;

                p.onclick = (e) => {
                    e.stopPropagation();
state.speed = opt.value;
state.rateLabel = opt.text;

restartIfPlaying();
restore(state.rateLabel);
					boardRateEl.style.height = "";
                };

                boardRateEl.appendChild(p);
            });
        }

        boardRateEl.onclick = (e) => {
            e.stopPropagation();
            openMenu();
        };

document.addEventListener("click", e => {
    if (!boardRateEl.contains(e.target)) {
        restore(state.rateLabel);
    }
});

        restore("1X");
    }

    update();

    return { stop };
}

function openStoryboardPlayer(sb, activeBoard) {
    if (!sb) return;

    let boardLight = document.getElementById("board_light");

    if (!boardLight) {
        boardLight = document.createElement("div");
        boardLight.id = "board_light";
        document.body.appendChild(boardLight);
    }

    document.body.style.overflowY = "hidden";

    boardLight.innerHTML = `
        <div id="board_back"></div>

        <div id="board_content">

            <p id="exit_board">X</p>

            <div id="board_contain">

                <div id="board_wrap">

                    <img id="board_img" src="${sb.cover || "#"}">

                    <div id="board_rate">
                        <p class="b_rate" id="rate_active">1X</p>
                    </div>

                    <div id="forward">
                        <img src="Images/board_forward.svg">
                    </div>

                    <div id="backward">
                        <img src="Images/board_back.svg">
                    </div>

                    <div id="play_board">
                        <img src="Images/board_play.svg">
                    </div>

                    <div id="board_control">

                        <img id="con_act" src="Images/story_play.svg">

                        <div id="frames">
                            <div id="frame_slide"></div>
                        </div>

                        <div id="frame_count">
                            <a id="frame_number">1</a>
                        </div>

                    </div>

                </div>

                <p id="board_title">${sb.title || "Storyboard"}</p>
                <p id="board_date">${sb.date || ""}</p>

                <div id="board_display"></div>

            </div>

        </div>
    `;

    boardLight.__activeBoard = activeBoard;

    const player = createStoryboardPlayer(sb, boardLight);

    const close = () => {
        boardLight.remove();
        document.body.style.overflowY = "scroll";
        player.stop?.();
    };

    document.getElementById("board_back").onclick = close;
    document.getElementById("exit_board").onclick = close;

    // -----------------------------
    // TITLE EDIT CONTROL
    // -----------------------------

    const lockedDefaultBoards = [
        "def_aoe",
        "def_oxy",
        "def_chaos"
    ];

    const isDefaultStoryboard =
        activeBoard &&
        lockedDefaultBoards.includes(activeBoard.id);

    // only allow editing for user-created .board storyboards
    if (isDefaultStoryboard) return;

    const boardContent = document.getElementById("board_content");

    boardContent.addEventListener("click", (e) => {

        const titleEl = e.target.closest("#board_title");
        if (!titleEl) return;

        e.stopPropagation();

        // prevent duplicate editor
        if (document.getElementById("board_title_wrap")) return;

        const boardDisplay = document.getElementById("board_display");

        if (boardDisplay) {
            boardDisplay.style.top = "27em";
        }

        const currentText = titleEl.textContent.trim();

        const wrap = document.createElement("div");
        wrap.id = "board_title_wrap";

        const input = document.createElement("input");
        input.id = "board_title_input";
        input.type = "text";
        input.value = "";
        input.placeholder = currentText;
        input.maxLength = 60;

        const btn = document.createElement("button");
        btn.id = "board_title_submit";
        btn.textContent = "SAVE";

        wrap.append(input, btn);

        titleEl.replaceWith(wrap);

        input.focus();

        let committed = false;

        function commit(forceText = null) {

            if (committed) return;
            committed = true;

            const newTitle =
                forceText !== null
                    ? forceText
                    : input.value.trim() || currentText;

            const newTitleEl = document.createElement("p");
            newTitleEl.id = "board_title";
            newTitleEl.textContent = newTitle;

            wrap.replaceWith(newTitleEl);

            if (boardDisplay) {
                boardDisplay.style.top = "";
            }

            const board = boardLight.__activeBoard;

            // update only user-created storyboard cards
            if (board && board.classList.contains("board")) {

                board.dataset.title = newTitle;

                const infoTitle = board.querySelector(".info_title");

                if (infoTitle) {
                    infoTitle.textContent = newTitle;
                }
            }
        }

        btn.onclick = (e) => {
            e.stopPropagation();
            commit();
        };

        input.addEventListener("keydown", (e) => {

            if (e.key === "Enter") {
                commit();
            }

            if (e.key === "Escape") {
                commit(currentText);
            }
        });

        input.addEventListener("blur", () => {
            setTimeout(() => {
                if (document.body.contains(wrap)) {
                    commit();
                }
            }, 100);
        });
    });
}